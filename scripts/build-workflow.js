#!/usr/bin/env node
'use strict';

/**
 * Generates workflow.json from the modules in src/.
 *
 * Every Code node embeds the same tested modules from src/, wrapped in an
 * isolated scope, so what runs in n8n matches what the Jest suite tests.
 * Edit src/ and re-run `npm run build:workflow`. Do not hand-edit Code nodes.
 *
 *   node scripts/build-workflow.js           write workflow.json
 *   node scripts/build-workflow.js --check   exit 1 if workflow.json is stale
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'workflow.json');
const { STAGES } = require('../src/conflict-resolver');

const CREDENTIAL = { hubspotAppToken: { id: 'REPLACE_WITH_N8N_CREDENTIAL_ID', name: 'HubSpot Private App Token' } };
const API_BASE = "{{ $env.HUBSPOT_API_BASE_URL || 'https://api.hubapi.com' }}";

function stableId(name) {
  const h = crypto.createHash('sha256').update(`n8n-hubspot-contact-merge-conflict-resolver:${name}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function embed(varName, file) {
  const src = fs.readFileSync(path.join(ROOT, 'src', file), 'utf8').trim();
  return [
    `// ---- embedded from src/${file} (generated, do not edit here) ----`,
    `const ${varName} = (() => {`,
    '  const module = { exports: {} };',
    src,
    '  return module.exports;',
    '})();',
    '',
  ].join('\n');
}

function codeBody(modules, entry) {
  const header = '// AUTO-GENERATED by scripts/build-workflow.js. Edit src/ and rebuild instead.\n';
  return header + modules.map(([v, f]) => embed(v, f)).join('\n') + '\n// ---- node entry ----\n' + entry.trim() + '\n';
}

const RESOLVER = [['resolver', 'conflict-resolver.js']];
const ALL = [['signature', 'hubspot-signature.js'], ['events', 'event-filter.js'], ...RESOLVER];

const ENTRY = {
  verify: `
const config = resolver.loadConfig($env);
const item = $input.first();
const headers = item.json.headers || {};

let rawBody;
let rawBodySource = 'binary';
try {
  const buffer = await this.helpers.getBinaryDataBuffer(0, 'data');
  rawBody = buffer.toString('utf8');
} catch (error) {
  // The Webhook node's "Raw Body" option is off. Re-serialising usually matches HubSpot's compact JSON, but not always.
  rawBodySource = 'reserialized_json';
  rawBody = JSON.stringify(item.json.body === undefined ? null : item.json.body);
}

const verification = resolver.shouldSkipSignature(config)
  ? { valid: true, reason: 'skipped_in_sandbox_mode' }
  : signature.verifySignatureV3({
      method: 'POST',
      uri: config.webhookPublicUrl,
      body: rawBody,
      timestamp: headers['x-hubspot-request-timestamp'],
      signature: headers['x-hubspot-signature-v3'],
      clientSecret: $env.HUBSPOT_CLIENT_SECRET,
      maxAgeMs: config.signatureMaxAgeMs,
    });

if (!verification.valid) {
  return [{ json: { valid: false, reason: verification.reason, rawBodySource } }];
}

let body;
try { body = JSON.parse(rawBody); } catch (error) { body = item.json.body; }
const parsed = events.parseEvents(body, config);
return [{ json: { valid: true, verification: verification.reason, rawBodySource, events: parsed.events, skipped: parsed.skipped } }];
`,
  split: `
const config = resolver.loadConfig($env);
const readProperties = resolver.readProperties(config).join(',');
const batch = $input.first().json;
return (batch.events || []).map((event) => ({ json: { ...event, readProperties } }));
`,
  buildSearch: `
const config = resolver.loadConfig($env);
const items = $input.all();
const out = [];
for (let i = 0; i < items.length; i++) {
  const contact = items[i].json;
  const event = $('Split Events').itemMatching(i).json;
  if (String(contact.id) !== String(event.objectId) || contact.archived) {
    console.log('[merge-resolver] skip: trigger contact already merged or archived', event.objectId);
    continue;
  }
  const searchBody = resolver.buildSearchRequest(contact, config);
  if (!searchBody) {
    console.log('[merge-resolver] skip: no searchable identity fields', event.objectId);
    continue;
  }
  out.push({ json: { event, triggerContact: contact, searchBody }, pairedItem: { item: i } });
}
return out;
`,
  buildRead: `
const config = resolver.loadConfig($env);
const items = $input.all();
const out = [];
for (let i = 0; i < items.length; i++) {
  const ctx = $('Build Search Request').itemMatching(i).json;
  const response = items[i].json;
  const readBody = resolver.buildClusterReadRequest(ctx.triggerContact, response, config);
  if (!readBody) {
    console.log('[merge-resolver] no candidates found', ctx.event.objectId);
    continue;
  }
  out.push({ json: { event: ctx.event, searchTotal: Number(response.total) || 0, readBody }, pairedItem: { item: i } });
}
return out;
`,
  resolve: `
const config = resolver.loadConfig($env);
const items = $input.all();
const out = [];
for (let i = 0; i < items.length; i++) {
  const ctx = $('Build Cluster Read').itemMatching(i).json;
  const records = items[i].json.results || [];
  const decision = resolver.resolveCluster({ triggerId: ctx.event.objectId, records, searchTotal: ctx.searchTotal, config });
  const primary = records.find((r) => String(r.id) === String(decision.primaryId));
  const primaryEmail = primary && primary.properties ? primary.properties.email || null : null;
  out.push({ json: { event: ctx.event, decision, primaryEmail }, pairedItem: { item: i } });
}
return out;
`,
  verifyMerge: `
const items = $input.all();
const out = [];
for (let i = 0; i < items.length; i++) {
  const ctx = $('Resolve Conflict').itemMatching(i).json;
  const verification = resolver.verifyMergeOutcome(ctx.decision, items[i].json, ctx.primaryEmail);
  const audit = resolver.buildAuditEntry(ctx.decision, {
    event: ctx.event,
    outcome: verification.ok ? 'merged' : 'merged_with_mismatch',
    verification,
  });
  const ticket = verification.ok ? null : resolver.buildVerificationTicket(ctx.decision, verification, { event: ctx.event });
  out.push({ json: { audit, ticket }, pairedItem: { item: i } });
}
return out;
`,
  dryRunAudit: `
return $input.all().map((item, i) => ({
  json: { audit: resolver.buildAuditEntry(item.json.decision, { event: item.json.event, outcome: 'dry_run' }) },
  pairedItem: { item: i },
}));
`,
  reviewTicket: `
return $input.all().map((item, i) => ({
  json: { ticket: resolver.buildReviewTicket(item.json.decision, { event: item.json.event }) },
  pairedItem: { item: i },
}));
`,
  classifyError: `
const stage = $prevNode.name;
const items = $input.all();
const out = [];
for (let i = 0; i < items.length; i++) {
  let event = null;
  let decision = null;
  try { event = $('Split Events').itemMatching(i).json; } catch (e) { /* not reached yet */ }
  try { decision = $('Resolve Conflict').itemMatching(i).json.decision; } catch (e) { /* not reached yet */ }
  const error = items[i].json.error !== undefined ? items[i].json.error : items[i].json;
  const ticket = resolver.buildErrorTicket({ stage, error, event, decision });
  if (!ticket) {
    console.log('[merge-resolver] ignorable error at', stage, event && event.objectId);
    continue;
  }
  out.push({ json: { ticket }, pairedItem: { item: i } });
}
return out;
`,
  workflowFailure: `
return [{ json: { ticket: resolver.buildWorkflowFailureTicket($input.first().json) } }];
`,
};

// ---------------------------------------------------------------------------
// Node factories
// ---------------------------------------------------------------------------

function codeNode(name, position, modules, entry) {
  return {
    parameters: { mode: 'runOnceForAllItems', jsCode: codeBody(modules, entry) },
    id: stableId(name), name, type: 'n8n-nodes-base.code', typeVersion: 2, position,
  };
}

function hubspotRequest(name, position, { method, url, query, body }) {
  const parameters = {
    method,
    url: `=${API_BASE}${url}`,
    authentication: 'predefinedCredentialType',
    nodeCredentialType: 'hubspotAppToken',
    options: { timeout: 20000 },
  };
  if (query) {
    parameters.sendQuery = true;
    parameters.queryParameters = { parameters: query.map(([n, v]) => ({ name: n, value: v })) };
  }
  if (body) {
    parameters.sendBody = true;
    parameters.specifyBody = 'json';
    parameters.jsonBody = body;
  }
  return {
    parameters, id: stableId(name), name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position,
    credentials: CREDENTIAL, retryOnFail: true, maxTries: 3, waitBetweenTries: 3000, onError: 'continueErrorOutput',
  };
}

function outboundWebhook(name, position, envVar, field) {
  return {
    parameters: {
      method: 'POST',
      url: `={{ $env.${envVar} }}`,
      sendBody: true,
      specifyBody: 'json',
      jsonBody: `={{ JSON.stringify($json.${field}) }}`,
      options: { timeout: 10000 },
    },
    id: stableId(name), name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position,
    retryOnFail: true, maxTries: 3, waitBetweenTries: 2000, onError: 'continueRegularOutput',
  };
}

function condition(leftValue, operator, rightValue = '') {
  return {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
    conditions: [{ id: stableId(`cond:${leftValue}:${rightValue}`), leftValue, rightValue, operator }],
    combinator: 'and',
  };
}

const IS_TRUE = { type: 'boolean', operation: 'true', singleValue: true };
const STR_EQ = { type: 'string', operation: 'equals' };

function ifNode(name, position, leftValue) {
  return {
    parameters: { conditions: condition(leftValue, IS_TRUE), options: {} },
    id: stableId(name), name, type: 'n8n-nodes-base.if', typeVersion: 2, position,
  };
}

function respondNode(name, position, code, body) {
  return {
    parameters: { respondWith: 'json', responseBody: body, options: { responseCode: code } },
    id: stableId(name), name, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.1, position,
  };
}

