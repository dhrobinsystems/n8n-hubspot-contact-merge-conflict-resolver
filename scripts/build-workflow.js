function buildWorkflow() {
  const nodes = [
    {
      parameters: {
        content: [
          '## HubSpot Contact Merge Conflict Resolver',
          'Webhook-driven deduplication sentinel.',
          '',
          '**Before activating:**',
          '1. Set the env vars from `.env.example` on the n8n host',
          '2. Attach a HubSpot Private App Token credential to every HubSpot node',
          '3. Settings → Error workflow → this workflow',
          '4. Keep `DRY_RUN=true` until the audit log looks right',
          '',
          'Code nodes are generated from `src/`. Edit `src/` and run `npm run build:workflow`.',
        ].join('\n'),
        height: 300, width: 420,
      },
      id: stableId('Readme Note'), name: 'Readme Note', type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: [-40, -60],
    },
    {
      parameters: {
        httpMethod: 'POST',
        path: 'hubspot/contact-merge-resolver',
        responseMode: 'responseNode',
        options: { rawBody: true },
      },
      id: stableId('HubSpot Webhook'), name: 'HubSpot Webhook', type: 'n8n-nodes-base.webhook', typeVersion: 2,
      position: [0, 400], webhookId: stableId('webhook-path'),
    },
    codeNode('Verify Signature & Parse Events', [220, 400], ALL, ENTRY.verify),
    ifNode('Signature Valid?', [440, 400], '={{ $json.valid }}'),
    respondNode('Respond 200 Accepted', [660, 300], 200,
      '={{ JSON.stringify({ received: true, accepted: $json.events.length, skipped: $json.skipped.length }) }}'),
    respondNode('Respond 401 Rejected', [660, 520], 401,
      '={{ JSON.stringify({ received: false, reason: $json.reason }) }}'),
    codeNode('Split Events', [880, 300], RESOLVER, ENTRY.split),
    {
      parameters: { amount: 10, unit: 'seconds' },
      id: stableId('Wait for Search Index'), name: 'Wait for Search Index', type: 'n8n-nodes-base.wait', typeVersion: 1.1,
      position: [1100, 300], webhookId: stableId('wait-webhook'),
    },
    hubspotRequest(STAGES.FETCH_TRIGGER, [1320, 300], {
      method: 'GET',
      url: '/crm/v3/objects/contacts/{{ $json.objectId }}',
      query: [['properties', '={{ $json.readProperties }}'], ['archived', 'false']],
    }),
    codeNode('Build Search Request', [1540, 300], RESOLVER, ENTRY.buildSearch),
    hubspotRequest(STAGES.SEARCH, [1760, 300], {
      method: 'POST', url: '/crm/v3/objects/contacts/search', body: '={{ JSON.stringify($json.searchBody) }}',
    }),
    codeNode('Build Cluster Read', [1980, 300], RESOLVER, ENTRY.buildRead),
    hubspotRequest(STAGES.READ_CLUSTER, [2200, 300], {
      method: 'POST', url: '/crm/v3/objects/contacts/batch/read', body: '={{ JSON.stringify($json.readBody) }}',
    }),
    codeNode('Resolve Conflict', [2420, 300], RESOLVER, ENTRY.resolve),
    {
      parameters: {
        rules: {
          values: ['merge', 'review', 'dry_run'].map((action) => ({
            conditions: condition('={{ $json.decision.action }}', STR_EQ, action),
            renameOutput: true,
            outputKey: action,
          })),
        },
        options: { fallbackOutput: 'extra', renameFallbackOutput: 'none_or_skip' },
      },
      id: stableId('Route Decision'), name: 'Route Decision', type: 'n8n-nodes-base.switch', typeVersion: 3, position: [2640, 300],
    },
    ifNode('Has Backfill?', [2860, 60], '={{ $json.decision.hasBackfill }}'),
    hubspotRequest(STAGES.BACKFILL, [3080, -40], {
      method: 'PATCH',
      url: '/crm/v3/objects/contacts/{{ $json.decision.primaryId }}',
      body: '={{ JSON.stringify({ properties: $json.decision.backfill.properties }) }}',
    }),
    hubspotRequest(STAGES.MERGE, [3300, 60], {
      method: 'POST',
      url: '/crm/v3/objects/contacts/merge',
      body: "={{ JSON.stringify($('Resolve Conflict').item.json.decision.mergePayload) }}",
    }),
    hubspotRequest(STAGES.FETCH_MERGED, [3520, 60], {
      method: 'GET',
      url: '/crm/v3/objects/contacts/{{ $json.id }}',
      query: [['properties', "={{ ['email', 'hs_merged_object_ids'].concat(Object.keys($('Resolve Conflict').item.json.decision.backfill.properties)).join(',') }}"]],
    }),
    codeNode('Verify Merge Outcome', [3740, 60], RESOLVER, ENTRY.verifyMerge),
    ifNode('Verification Failed?', [3960, -60], '={{ $json.ticket !== null }}'),
    codeNode('Build Review Ticket', [2860, 340], RESOLVER, ENTRY.reviewTicket),
    codeNode('Build Dry-Run Audit', [2860, 540], RESOLVER, ENTRY.dryRunAudit),
    { parameters: {}, id: stableId('No Action Needed'), name: 'No Action Needed', type: 'n8n-nodes-base.noOp', typeVersion: 1, position: [2860, 740] },
    outboundWebhook('Write Audit Log', [4180, 200], 'AUDIT_LOG_WEBHOOK_URL', 'audit'),
    outboundWebhook('Send to Review Queue', [4400, 440], 'REVIEW_QUEUE_WEBHOOK_URL', 'ticket'),
    codeNode('Classify API Error', [3960, 700], RESOLVER, ENTRY.classifyError),
    {
      parameters: {}, id: stableId('Error Trigger'), name: 'Error Trigger', type: 'n8n-nodes-base.errorTrigger', typeVersion: 1, position: [3740, 940],
    },
    codeNode('Format Workflow Failure', [3960, 940], RESOLVER, ENTRY.workflowFailure),
  ];

  const to = (node, index = 0) => ({ node, type: 'main', index });
  const connections = {
    'HubSpot Webhook': { main: [[to('Verify Signature & Parse Events')]] },
    'Verify Signature & Parse Events': { main: [[to('Signature Valid?')]] },
    'Signature Valid?': { main: [[to('Respond 200 Accepted')], [to('Respond 401 Rejected')]] },
    'Respond 200 Accepted': { main: [[to('Split Events')]] },
    'Split Events': { main: [[to('Wait for Search Index')]] },
    'Wait for Search Index': { main: [[to(STAGES.FETCH_TRIGGER)]] },
    [STAGES.FETCH_TRIGGER]: { main: [[to('Build Search Request')], [to('Classify API Error')]] },
    'Build Search Request': { main: [[to(STAGES.SEARCH)]] },
    [STAGES.SEARCH]: { main: [[to('Build Cluster Read')], [to('Classify API Error')]] },
    'Build Cluster Read': { main: [[to(STAGES.READ_CLUSTER)]] },
    [STAGES.READ_CLUSTER]: { main: [[to('Resolve Conflict')], [to('Classify API Error')]] },
    'Resolve Conflict': { main: [[to('Route Decision')]] },
    'Route Decision': {
      main: [[to('Has Backfill?')], [to('Build Review Ticket')], [to('Build Dry-Run Audit')], [to('No Action Needed')]],
    },
    'Has Backfill?': { main: [[to(STAGES.BACKFILL)], [to(STAGES.MERGE)]] },
    [STAGES.BACKFILL]: { main: [[to(STAGES.MERGE)], [to('Classify API Error')]] },
    [STAGES.MERGE]: { main: [[to(STAGES.FETCH_MERGED)], [to('Classify API Error')]] },
    [STAGES.FETCH_MERGED]: { main: [[to('Verify Merge Outcome')], [to('Classify API Error')]] },
    'Verify Merge Outcome': { main: [[to('Write Audit Log'), to('Verification Failed?')]] },
    'Verification Failed?': { main: [[to('Send to Review Queue')], []] },
    'Build Review Ticket': { main: [[to('Send to Review Queue')]] },
    'Build Dry-Run Audit': { main: [[to('Write Audit Log')]] },
    'Classify API Error': { main: [[to('Send to Review Queue')]] },
    'Error Trigger': { main: [[to('Format Workflow Failure')]] },
    'Format Workflow Failure': { main: [[to('Send to Review Queue')]] },
  };

  return {
    name: 'HubSpot Contact Merge Conflict Resolver',
    nodes,
    pinData: {},
    connections,
    active: false,
    settings: { executionOrder: 'v1', saveManualExecutions: true, saveDataErrorExecution: 'all', callerPolicy: 'workflowsFromSameOwner' },
    versionId: stableId('version-1.0.0'),
    meta: { templateCredsSetupCompleted: false },
    tags: [],
  };
}

function render() {
  return `${JSON.stringify(buildWorkflow(), null, 2)}\n`;
}

if (require.main === module) {
  const output = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== output) {
      console.error('workflow.json is out of date. Run: npm run build:workflow');
      process.exit(1);
    }
    console.log('workflow.json is up to date.');
  } else {
    fs.writeFileSync(OUTPUT, output);
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${buildWorkflow().nodes.length} nodes)`);
  }
}

module.exports = { buildWorkflow, render };
